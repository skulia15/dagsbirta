#!/bin/bash
# Dagsbirta Project Setup Script
# Run this once before starting Ralph

set -e

echo "🚀 Dagsbirta Project Setup"
echo "================================"

# 1. Install missing dependencies
echo "📦 Installing dependencies..."
npm install sharp @types/sharp vitest @vitest/ui

# 2. Create directory structure
echo "📁 Creating directory structure..."
mkdir -p src/lib/calculations
mkdir -p src/lib/tiles
mkdir -p src/lib/pdf
mkdir -p src/components/map
mkdir -p src/components/controls
mkdir -p src/components/visualizations
mkdir -p src/components/results
mkdir -p src/i18n
mkdir -p data/dem/raw
mkdir -p data/dem/tiles
mkdir -p scripts

# 3. Download sample DEM data from LMÍ
echo "🗺️  Downloading DEM data from https://ftp.lmi.is/gisdata/raster/ ..."
echo "   (This may take a few minutes)"

# Download ÍslandsDEM 10m for Reykjavík area (example - adjust as needed)
# Note: You may need to manually download from FTP browser
echo "   ⚠️  Manual step required:"
echo "   Visit: https://ftp.lmi.is/gisdata/raster/"
echo "   Download: ÍslandsDEM (10m resolution)"
echo "   Place GeoTIFF files in: data/dem/raw/"
echo ""
echo "   Press Enter when DEM files are in data/dem/raw/ ..."
read -r

# Verify DEM files exist
if [ -z "$(ls -A data/dem/raw/)" ]; then
   echo "❌ No DEM files found in data/dem/raw/"
   echo "   Please download files from https://ftp.lmi.is/gisdata/raster/ first"
   exit 1
fi

echo "✅ DEM files found: $(ls data/dem/raw/ | wc -l) file(s)"

# 4. Create TypeScript types file
echo "📝 Creating TypeScript types..."
cat > src/types/index.ts << 'EOF'
// Dagsbirta - Shared TypeScript Types
// Generated by setup script

export interface HorizonPoint {
  azimuth: number;        // 0-360 degrees, 0=North
  elevationAngle: number; // degrees above horizontal
  distance: number;       // km to horizon point
  peakElevation: number;  // absolute elevation of blocking terrain
}

export interface HorizonProfile {
  location: { lat: number; lng: number; elevation: number };
  profile: HorizonPoint[];
  computedAt: Date;
}

export interface SunPosition {
  altitude: number;  // degrees above horizon
  azimuth: number;   // degrees from north
  date: Date;
}

export interface SunPath {
  date: Date;
  positions: SunPosition[];
  sunrise: Date | null;
  sunset: Date | null;
  solarNoon: Date;
  dayLengthHours: number;
  isMidnightSun: boolean;
  isPolarNight: boolean;
}

export interface ShadowResult {
  isVisible: boolean;
  sunAltitude: number;
  horizonAltitude: number;
  margin: number;
}

export interface DailySunlight {
  date: Date;
  location: { lat: number; lng: number };
  totalHours: number;
  theoreticalHours: number;
  reductionHours: number;
  reductionPercent: number;
  terrainSunrise: Date | null;
  terrainSunset: Date | null;
  astronomicalSunrise: Date | null;
  astronomicalSunset: Date | null;
  intervals: Array<{
    time: Date;
    isVisible: boolean;
    sunAltitude: number;
  }>;
}

export interface MonthlySunlight {
  month: number;
  monthName: string;
  year: number;
  averageDailyHours: number;
  totalHours: number;
  theoreticalHours: number;
  reductionPercent: number;
}

export interface AnnualSunlight {
  year: number;
  months: MonthlySunlight[];
  totalHours: number;
  averageDailyHours: number;
  theoreticalTotalHours: number;
  reductionPercent: number;
}

export interface IrradianceResult {
  annualGHI: number;
  annualPOA: number;
  optimalTiltAngle: number;
  monthlyIrradiance: Array<{
    month: number;
    ghi: number;
    poa: number;
  }>;
}

export interface SolarROIResult {
  systemSizeKW: number;
  panelAreaM2: number;
  annualProductionKWh: number;
  monthlyProduction: Array<{ month: number; kWh: number }>;
  annualSavingsEUR: number;
  installCostEUR: number;
  paybackYears: number;
  return25Year: number;
  roiPercent: number;
  isViable: boolean;
  viabilityRating: 'excellent' | 'good' | 'marginal' | 'poor';
}
EOF

# 5. Create constants file
echo "⚙️  Creating constants..."
cat > src/lib/constants.ts << 'EOF'
// Dagsbirta - Iceland-Specific Constants
// Generated by setup script

export const ICELAND_BOUNDS = {
  north: 66.5,
  south: 63.3,
  west: -24.5,
  east: -13.5
} as const;

export const SOLAR_CONSTANTS = {
  panelEfficiency: 0.20,
  systemLosses: 0.14,
  electricityPriceEUR: 0.18,
  installCostPerKW: 1500,
  annualDegradation: 0.005,
  systemLifeYears: 25
} as const;

export const DEM_CONFIG = {
  zoomLevels: { min: 8, max: 14 },
  tileSize: 256,
  resolution: 10, // meters
  radiusKm: 50 // horizon search radius
} as const;

export const CALCULATION_CONFIG = {
  horizonResolutionDegrees: 1,
  sunPathIntervalMinutes: 5,
  monthlyTimeout: 5000 // ms
} as const;
EOF

# 6. Update package.json scripts (if json command available)
echo "📋 Adding test scripts to package.json..."
if command -v json &> /dev/null; then
  npx json -I -f package.json -e 'this.scripts.test="vitest"'
  npx json -I -f package.json -e 'this.scripts["test:ui"]="vitest --ui"'
else
  echo "   ⚠️  'json' command not found. Manually add to package.json:"
  echo '   "test": "vitest",'
  echo '   "test:ui": "vitest --ui"'
fi

# 7. Create .gitignore additions
echo "🚫 Updating .gitignore..."
cat >> .gitignore << 'EOF'

# DEM data (large files)
data/dem/raw/*.tif
data/dem/tiles/**/*.png

# Ralph logs
ralph-*.log
EOF

echo ""
echo "✅ Setup complete!"
echo ""
echo "Next steps:"
echo "1. Verify DEM data exists: ls data/dem/raw/"
echo "2. Run Ralph multi-task prompt (see plan file)"
echo "3. Monitor progress with: git log --oneline"
echo ""
